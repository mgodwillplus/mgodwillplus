/* ---------------------------------------------------------
   MGDOWILL+ HELPER FUNCTIONS
   --------------------------------------------------------- */

/*
   Return every media item in one array.

   This makes it easier for the rest of the website to search
   through videos, songs and podcasts without modifying the
   original catalogue structure.
*/
function getAllMedia() {

    const videos = Array.isArray(MGODWILL_CATALOGUE.videos)
        ? MGODWILL_CATALOGUE.videos
        : [];

    const audio = Array.isArray(MGODWILL_CATALOGUE.audio)
        ? MGODWILL_CATALOGUE.audio
        : [];

    return [...videos, ...audio];
}


/*
   Find one media item by its unique ID.
*/
function getMediaById(id) {

    if (!id) {
        return null;
    }

    return getAllMedia().find(function(item) {
        return item.id === id;
    }) || null;
}


/*
   Convert a Google Drive "view" URL into a Drive preview URL.

   Example:
   /file/d/ABC/view
   becomes:
   /file/d/ABC/preview
*/
function getDrivePreviewUrl(url) {

    if (!url || typeof url !== "string") {
        return "";
    }

    const match = url.match(/\/file\/d\/([^/]+)/);

    if (!match) {
        return url;
    }

    return "https://drive.google.com/file/d/" + match[1] + "/preview";
}


/*
   Convert a Google Drive file URL into a thumbnail URL.

   This is particularly useful for the thumbnails you prepared
   for the catalogue.
*/
function getDriveThumbnailUrl(url) {

    if (!url || typeof url !== "string") {
        return "";
    }

    const match = url.match(/\/file\/d\/([^/]+)/);

    if (!match) {
        return url;
    }

    return "https://drive.google.com/thumbnail?id=" +
        match[1] +
        "&sz=w1200";
}


/*
   Mavuno Church has one dedicated image.

   Every item belonging to the Mavuno Church category therefore
   receives the same thumbnail, regardless of the individual
   thumbnail originally supplied.
*/
function getMediaThumbnail(item) {

    if (!item) {
        return "";
    }

    if (
        typeof item.category === "string" &&
        item.category.toLowerCase() === "mavuno church"
    ) {
        return getDriveThumbnailUrl(
            MGODWILL_CATALOGUE.site.mavunoChurchImage
        );
    }

    if (item.thumbnail) {
        return getDriveThumbnailUrl(item.thumbnail);
    }

    return "";
}


/*
   Return a media item's first playable URL.

   The "Anger" podcast contains two Drive links. The player
   system can later expose both rather than silently discarding
   one of them.
*/
function getPrimaryMediaUrl(item) {

    if (!item || !item.media) {
        return "";
    }

    if (Array.isArray(item.media)) {
        return item.media.length > 0
            ? item.media[0]
            : "";
    }

    return item.media;
}


/*
   Return all media URLs belonging to an item.
*/
function getMediaUrls(item) {

    if (!item || !item.media) {
        return [];
    }

    if (Array.isArray(item.media)) {
        return item.media.filter(function(url) {
            return typeof url === "string" && url.trim() !== "";
        });
    }

    return [item.media];
}


/*
   Return media grouped by category.
*/
function getMediaCategories() {

    const categories = [];

    getAllMedia().forEach(function(item) {

        if (
            item &&
            item.category &&
            !categories.includes(item.category)
        ) {
            categories.push(item.category);
        }

    });

    return categories;
}


/*
   Search the complete media catalogue.

   The search examines:
   - title
   - description
   - category
   - type
*/
function searchMedia(query) {

    if (!query || typeof query !== "string") {
        return getAllMedia();
    }

    const term = query.trim().toLowerCase();

    if (!term) {
        return getAllMedia();
    }

    return getAllMedia().filter(function(item) {

        const searchableText = [
            item.title,
            item.description,
            item.category,
            item.type
        ]
        .filter(Boolean)
        .join(" ")
        .toLowerCase();

        return searchableText.includes(term);
    });
}
